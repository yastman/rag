"""CRM card callback handlers for quick actions (#697 Task 8 / #2053 migration).

Router for crm:* inline keyboard callbacks generated by crm_cards.py:

* ``crm:lead:note:{id}`` — quick note to lead → starts ``CrmQuickActionsDialog``
  on ``waiting_note`` with ``entity_type="leads"``.
* ``crm:lead:task:{id}`` — quick task for lead → starts ``waiting_task``.
* ``crm:contact:note:{id}`` — quick note to contact → starts ``waiting_note``
  with ``entity_type="contacts"``.
* ``crm:task:edit:{id}`` — start task edit flow → starts
  ``edit_task_choose_field`` (Select picker), then forwards to
  ``edit_task_text`` or ``edit_task_date``.
* ``crm:task:complete:{id}`` — immediate complete (no dialog).
* ``crm:task:postpone:{id}`` — immediate +1 day postpone (no dialog).

Issue #2053: the FSM-based ``state.set_state(...)`` + ``StateFilter``
message handlers were replaced by the aiogram-dialog ``CrmQuickActionsDialog``
in ``telegram_bot/dialogs/crm_quick_actions.py``. This module is now a thin
trigger layer that calls ``dialog_manager.start(...)`` to enter the dialog.
"""

from __future__ import annotations

import datetime
import logging
import time
from typing import Any

from aiogram import F, Router
from aiogram.types import CallbackQuery, InaccessibleMessage
from aiogram_dialog import DialogManager, ShowMode, StartMode

from telegram_bot.dialogs.states import CrmQuickActionSG
from telegram_bot.observability import get_client, observe
from telegram_bot.services.kommo_models import TaskUpdate


logger = logging.getLogger(__name__)

_NO_CRM = "⚠️ CRM недоступна."


def _update_current_span(lf: Any, **kwargs: Any) -> None:
    """Update the current Langfuse span when tracing is available."""
    if lf is not None:
        lf.update_current_span(**kwargs)


async def _start_quick_action(
    dialog_manager: DialogManager,
    state: Any,
    data: dict[str, Any],
) -> None:
    """Start CrmQuickActionsDialog with RESET_STACK and SEND show mode.

    The trigger callbacks come from inline-keyboard buttons posted on top of
    a CRM card; opening the dialog as a fresh top-of-stack lets the user
    cancel back to the bot without ending up in an unrelated parent dialog.
    """
    await dialog_manager.start(
        state,
        data=data,
        mode=StartMode.RESET_STACK,
        show_mode=ShowMode.SEND,
    )


@observe(name="crm-lead-note-prompt", capture_input=False, capture_output=False)
async def on_lead_note(
    callback: CallbackQuery,
    dialog_manager: DialogManager,
    kommo_client: Any | None = None,
) -> None:
    """Handle crm:lead:note:{id} — start quick note dialog for a lead."""
    lf = get_client()
    if kommo_client is None:
        _update_current_span(lf, output={"action": "cancelled"})
        await callback.answer(_NO_CRM, show_alert=True)
        return
    assert callback.data is not None  # ensured by F.data.regexp filter
    lead_id = int(callback.data.split(":")[3])
    _update_current_span(lf, input={"deal_id": lead_id, "action": "lead-note-prompt"})
    await _start_quick_action(
        dialog_manager,
        CrmQuickActionSG.waiting_note,
        data={"entity_type": "leads", "entity_id": lead_id},
    )
    await callback.answer()


