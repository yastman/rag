@observe(name="crm-quick-complete", capture_input=False, capture_output=False)
async def on_task_complete(
    callback: CallbackQuery,
    kommo_client: Any | None = None,
) -> None:
    """Handle crm:task:complete:{id} — complete task immediately (no dialog)."""
    lf = get_client()
    if kommo_client is None:
        _update_current_span(lf, output={"action": "cancelled"})
        await callback.answer(_NO_CRM, show_alert=True)
        return
    assert callback.data is not None
    task_id = int(callback.data.split(":")[3])
    _update_current_span(lf, input={"task_id": task_id, "action": "complete"})
    try:
        await kommo_client.complete_task(task_id)
        _update_current_span(lf, output={"task_id": task_id, "status": "completed"})
        await callback.answer("✅ Задача завершена.")
        if callback.message and not isinstance(callback.message, InaccessibleMessage):
            await callback.message.edit_text("✅ Задача завершена.")
    except Exception as exc:
        logger.exception("Failed to complete task %d", task_id)
        _update_current_span(lf, level="ERROR", status_message=str(exc)[:200])
        await callback.answer("⚠️ Ошибка при завершении задачи.", show_alert=True)


@observe(name="crm-task-postpone", capture_input=False, capture_output=False)
async def on_task_postpone(
    callback: CallbackQuery,
    kommo_client: Any | None = None,
) -> None:
    """Handle crm:task:postpone:{id} — postpone task by +1 day (no dialog)."""
    lf = get_client()
    if kommo_client is None:
        _update_current_span(lf, output={"action": "cancelled"})
        await callback.answer(_NO_CRM, show_alert=True)
        return
    assert callback.data is not None
    task_id = int(callback.data.split(":")[3])
    _update_current_span(lf, input={"task_id": task_id, "action": "postpone"})
    due_ts = int(time.time()) + 86400
    try:
        await kommo_client.update_task(task_id, TaskUpdate(complete_till=due_ts))
        due_dt = datetime.datetime.fromtimestamp(due_ts, tz=datetime.UTC).strftime("%d.%m.%Y")
        msg = f"⏰ Задача отложена до {due_dt}."
        await callback.answer(msg)
        if callback.message and not isinstance(callback.message, InaccessibleMessage):
            await callback.message.edit_text(msg)
    except Exception as exc:
        logger.exception("Failed to postpone task %d", task_id)
        _update_current_span(lf, level="ERROR", status_message=str(exc)[:200])
        await callback.answer("⚠️ Ошибка при откладывании задачи.", show_alert=True)


def create_crm_router() -> Router:
    """Create router with CRM card action callback handlers.

    Note: FSM-based message handlers (waiting_note, waiting_task, edit_*) used
    to live here as ``StateFilter(CrmQuickActionSG.X)`` registrations. They
    moved into ``CrmQuickActionsDialog`` in
    ``telegram_bot/dialogs/crm_quick_actions.py`` (#2053). This router now
    only registers callback queries.
    """
    router = Router(name="crm_callbacks")

    # Immediate actions (no dialog required)
    router.callback_query(F.data.regexp(r"^crm:task:complete:\d+$"))(on_task_complete)
    router.callback_query(F.data.regexp(r"^crm:task:postpone:\d+$"))(on_task_postpone)

    # Dialog-triggering actions
    router.callback_query(F.data.regexp(r"^crm:lead:note:\d+$"))(on_lead_note)
    router.callback_query(F.data.regexp(r"^crm:lead:task:\d+$"))(on_lead_task)
    router.callback_query(F.data.regexp(r"^crm:contact:note:\d+$"))(on_contact_note)
    router.callback_query(F.data.regexp(r"^crm:task:edit:\d+$"))(on_task_edit)

    return router
